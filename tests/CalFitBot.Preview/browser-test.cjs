const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const artifacts=process.env.CALFITBOT_SCREENSHOTS||path.join(__dirname,'artifacts');
fs.mkdirSync(artifacts,{recursive:true});
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||(fs.existsSync('/usr/bin/chromium')?'/usr/bin/chromium':chromium.executablePath()),headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:412,height:915},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:3033');
 await page.getByRole('button',{name:'Submit sample meal',exact:true}).waitFor();
 await page.getByText('Connected. Press CAPTURE on CalFitBot to send a meal.',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'↑ Up',exact:true}).count(),0);
 assert.equal(await page.getByRole('button',{name:'Capture image',exact:true}).count(),0);
 await page.screenshot({path:path.join(artifacts,'bot-waiting.png'),fullPage:true});
 let baseline=await (await page.request.get('http://127.0.0.1:3033/test-counts')).json();
 await page.getByRole('button',{name:'Submit sample meal',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor();
 await page.getByRole('button',{name:'✦ Analyze Food',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='✦ Analyze Food').disabled);
 assert.equal(await page.locator('.bot-weight-summary strong').innerText(),'385 g');
 let counts=await (await page.request.get('http://127.0.0.1:3033/test-counts')).json();
 assert.equal(counts.analyze,baseline.analyze);assert.equal(counts.save,baseline.save);
 await page.screenshot({path:path.join(artifacts,'bot-received.png'),fullPage:true});
 await page.getByRole('button',{name:'✦ Analyze Food',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Meal details'});await dialog.waitFor();
 assert.equal(await page.locator('#food-name').inputValue(),'Simulated rice and chicken');
 assert.equal(await page.locator('#food-weight').inputValue(),'385');assert.equal(await page.locator('#food-weight').isDisabled(),true);
 await page.getByRole('button',{name:'Close meal details',exact:true}).click();
 await page.getByRole('button',{name:'Review meal',exact:true}).click();await dialog.waitFor();
 assert.equal(await page.locator('#food-name').inputValue(),'Simulated rice and chicken');
 await page.screenshot({path:path.join(artifacts,'bot-review.png'),fullPage:true});
 await page.getByRole('button',{name:'Save to my food journal →',exact:true}).click();
 await page.locator('#saved-result').waitFor();
 counts=await (await page.request.get('http://127.0.0.1:3033/test-counts')).json();
 assert.equal(counts.analyze,baseline.analyze+1);assert.equal(counts.save,baseline.save+1);
 await page.getByRole('button',{name:'Replay duplicate',exact:true}).click();
 await page.getByText('Duplicate submission acknowledged; no duplicate meal created.',{exact:true}).waitFor();
 counts=await (await page.request.get('http://127.0.0.1:3033/test-counts')).json();assert.equal(counts.save,baseline.save+1);
 await page.locator('#mock-scenario').selectOption('MissingWeight');
 await page.getByRole('button',{name:'Submit sample meal',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor();
 assert.equal(await page.locator('.bot-weight-summary strong').innerText(),'— g');
 await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='✦ Analyze Food').disabled);
 await page.getByRole('button',{name:'Discard received draft',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor({state:'detached'});
 await page.locator('#mock-scenario').selectOption('CanceledScan');
 await page.getByRole('button',{name:'Submit sample meal',exact:true}).click();
 await page.getByText('The scan was canceled or removed on the robot. Waiting for a new submission.',{exact:true}).waitFor();
 assert.equal(await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).count(),0);
 await page.getByRole('button',{name:'Test: other tab',exact:true}).click();
 await page.getByRole('button',{name:'Test: robot CAPTURE',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor();
 assert.equal(await page.locator('.bot-weight-summary strong').innerText(),'385 g');
 await page.waitForFunction(()=>!Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='✦ Analyze Food').disabled);
 await page.getByRole('button',{name:'Discard received draft',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor({state:'detached'});
 await page.getByRole('button',{name:'Test: other tab',exact:true}).click();
 await page.getByRole('button',{name:'Test: background / resume',exact:true}).click();
 await page.getByRole('button',{name:'Test: robot CAPTURE',exact:true}).click();
 await page.waitForTimeout(2300);
 assert.equal(await page.locator('#other-tab').count(),1);
 await page.getByRole('button',{name:'Test: background / resume',exact:true}).click();
 await page.getByRole('img',{name:'Food photo received from CalFitBot',exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS browser: waiting, receive photo/weight, no automatic AI/save, analyze, close/reopen draft, save once, duplicate, null weight, canceled scan, capture from another tab, background pause and resume; no page errors.');
})().catch(e=>{console.error(e);process.exit(1)});
